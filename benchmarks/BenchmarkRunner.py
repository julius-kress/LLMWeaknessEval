import os
import sys
from abc import abstractmethod, ABC
import time
import csv
import json
from datetime import datetime
from utils.evaluation_utils import run_bandit, run_codeql

from openai import OpenAI


class BenchmarkRunner(ABC):
    """
    Abstract base class for running the benchmarks. Provides connection to LLM, vulnerability scanners, logging.
    """
    def __init__(self):
        # Declare needed paths
        self.LOG_FILE = None
        self.LOGS_DIR = None
        self.RESULT_FILE = None
        self.SUMMARY_CSV = None
        self.JSON_OUTPUT_DIR = None

        self.client = OpenAI(
            api_key=os.getenv("LLM_API_KEY"),
            base_url="https://openrouter.ai/api/v1",
        )

        self.PROJECT_ROOT = os.path.abspath(os.path.join(__file__, "..", ".."))


    def init_folder_structure(self):
        """
        Initialize the folder structure.
        """
        self.JSON_OUTPUT_DIR = os.path.join(self.get_benchmark_root(), "results_json")  # For JSON files

        self.LOGS_DIR = os.path.join(self.get_benchmark_root(), "logs")
        self.LOG_FILE = os.path.join(self.LOGS_DIR, "generation_log.txt")
        self.RESULT_FILE = os.path.join(self.LOGS_DIR, "eval_result.csv")
        self.SUMMARY_CSV = os.path.join(self.LOGS_DIR, "results_summary.csv")

        os.makedirs(self.JSON_OUTPUT_DIR, exist_ok=True)
        os.makedirs(self.LOGS_DIR, exist_ok=True)

    def request_llm(self, prompt: str, model: str, retries=3, delay=3) -> str:
        """
        Send a prompt to the LLM with the instruction to generate only program code.
        :param prompt: The prompt to send to the LLM
        :param model: The model which should handle the prompt
        :param retries: Maximum retries
        :param delay: Delay after each retry
        :return: The response of the LLM as a string
        """
        for attempt in range(retries):
            try:
                response = self.client.chat.completions.create(
                    model=model,
                    messages=[
                        {"role": "system",
                         "content": "Handle the given problem and return as an answer only the code for the problem and nothing else. ONLY give back the code!"},
                        {"role": "user", "content": prompt},
                    ],
                    temperature=0.2,
                )

                return response.choices[0].message.content
            except Exception as e:
                self.save_log(f"Error: {e} - Retry {attempt + 1}/{retries}")
                time.sleep(delay)
        return ""

    def clean_python_code(self, content: str) -> str:
        """
        Cleans the python code generate by the LLM.
        :param content: The generated LLM response
        :return: Cleaned python code
        """
        content = content.lstrip()

        if content.startswith("```python"):
            content = content[len("```python"):]

        content = content.rstrip()

        if content.endswith("```"):
            content = content[:-3]

        return content.strip()

    def clear_result_file(self):
        """
        Clear the result file so on a new run the old data is deleted.
        """
        fieldnames = [
            "id",
            "prompt",
            "generated_code",
            "model",
            "bandit_evaluation",
            "codeql_evaluation",
        ]

        self.save_log(f"Clearing result file {self.RESULT_FILE}")

        with open(self.RESULT_FILE, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()

    def save_log(self, message: str):
        """
        Save a log message.
        :param message: The message to log.
        """
        print(message)
        with open(self.LOG_FILE, "a") as log_f:
            timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            log_f.write(f"[{timestamp}] {message}\n")

    def save_json_result(self, json_path: str, prompt_id, prompt, generated_code, model):
        """
        Save the response of the LLM as a json result.
        :param json_path: path to json file
        :param prompt_id: The prompt id in the benchmark
        :param prompt: The prompt that was sent to the LLM
        :param generated_code: The code generated by the LLM
        :param model: The model which was used
        """
        with open(json_path, "w") as f:
            json.dump({
                "id": prompt_id,
                "prompt": prompt,
                "generated_code": generated_code,
                "model": model,
            }, f, indent=2)

    @abstractmethod
    def get_benchmark_root(self) -> str:
        """
        Return the root folder of the current benchmark
        """
        pass

    @abstractmethod
    def generate_code(self, model: str):
        """
        Generate code for the given model -> entry from main method
        :param model: The model which should be used
        """
        pass

    def evaluate_results(self):
        """
        Evaluate the LLM generated code by running Bandit and CodeQL.
        """
        self.save_log(f"Evaluating results from {self.JSON_OUTPUT_DIR}")

        fields = [
            "id",
            "prompt",
            "generated_code",
            "model",
            "bandit_evaluation",
            "codeql_evaluation",
        ]

        csv.field_size_limit(sys.maxsize)
        # Check which tasks already have been evaluated and only evaluate the missing tasks
        existing = set()
        if os.path.exists(self.RESULT_FILE):
            with open(self.RESULT_FILE, "r", newline="", encoding="utf-8") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    existing.add((row["id"], row["model"]))

        with open(self.RESULT_FILE, "a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fields)

            if os.path.getsize(self.RESULT_FILE) == 0:
                writer.writeheader()

            files = sorted(os.listdir(self.JSON_OUTPUT_DIR))
            total = len(files)

            # Process all files with generated code
            for idx, json_file in enumerate(files, start=1):
                if json_file.endswith(".json"):
                    filepath = os.path.join(self.JSON_OUTPUT_DIR, json_file)
                    with open(filepath, "r", encoding="utf-8") as f:
                        data = json.load(f)

                record_id = data.get("id", "")
                prompt = data.get("prompt", "")
                generated_code = data.get("generated_code", "")
                model = data.get("model", "")

                # Check if current task already was evaluated
                key = (str(record_id), model)

                if key in existing:
                    continue


                self.save_log(f"{idx}/{total}: Running bandit for [{record_id}]")
                bandit_evaluation = run_bandit(generated_code)

                self.save_log(f"{idx}/{total}: Running CodeQL for [{record_id}]")
                codeql_evaluation = run_codeql(generated_code)

                writer.writerow({
                    "id": record_id,
                    "prompt": prompt,
                    "generated_code": generated_code,
                    "model": model,
                    "bandit_evaluation": bandit_evaluation,
                    "codeql_evaluation": codeql_evaluation,
                })

                # Mark current task as processed
                existing.add(key)

